#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

GAME_DIR="${1:-$DOSBOX_GAMES_DIR}"
GAME_NAME="${2:-$(basename "$GAME_DIR")}"

print_header "Configuring DOSBox for $GAME_NAME"

ensure_dir "$DOSBOX_ROOT"
ensure_dir "$DOSBOX_GAMES_DIR"
ensure_dir "$DOSBOX_CONFIG_DIR"
ensure_dir "$GAME_DIR"

cat > "$GAME_DIR/dosbox.conf" <<EOF
[sdl]
fullscreen=false
fulldouble=false
windowresolution=1280x720
output=opengl

[cpu]
core=auto
cputype=auto
cycles=25000

[mixer]
blocksize=1024
prebuffer=25

[dosbox]
memsize=32
machine=svga_s3

[autoexec]
mount C "$GAME_DIR"
C:
if exist START.BAT start /WAIT START.BAT
if exist AUTOEXEC.BAT autoexec.bat
EOF

cat > "$DOSBOX_CONFIG_DIR/$GAME_NAME.conf" <<EOF
# Generated by $SCRIPT_DIR/configure_dosbox.sh
[autoexec]
mount C "$GAME_DIR"
C:
EOF

cat <<EOF
DOSBox config created:
- Game directory: $GAME_DIR
- Shared config: $DOSBOX_CONFIG_DIR/$GAME_NAME.conf
- Per-game config: $GAME_DIR/dosbox.conf

To run the game:
  dosbox -conf "$GAME_DIR/dosbox.conf"
EOF
